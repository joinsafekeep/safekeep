// Checks content/practice-library/*.json and writes database/practice-seed.sql, which inserts every scenario as a
// draft version. Run with `npm run practice:seed`. Re-running the SQL is safe: scams that already exist are skipped.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const FORMATS = ['email', 'text', 'phone'];
// Real brands and agencies a practice must not name (PRD: impersonate roles, not companies). Not exhaustive; review
// still happens by hand.
const BRANDS = /\b(amazon|usps|ups|fedex|dhl|irs|social security administration|ssa\.gov|medicare\.gov|cms|chase|wells fargo|bank of america|citi|paypal|venmo|zelle|apple|microsoft|google|netflix|walmart|costco|norton|mcafee|geek squad|comcast|xfinity|verizon|at&t|facebook|meta)\b/i;
const BANNED_WORDS = /\b(fail(ed|ure)?|fell for|victim)\b/i;

export function validateScenario(s, format) {
 const problems = [];
 const need = ['code', 'name', 'category', 'difficulty', 'content', 'learning_objective', 'debrief'];
 for (const k of need) if (s[k] === undefined || s[k] === '') problems.push(`missing ${k}`);
 if (!/^[a-z0-9-]{3,60}$/.test(s.code || '')) problems.push('code must be lowercase words joined by hyphens');
 if (!(s.difficulty >= 1 && s.difficulty <= 5)) problems.push('difficulty must be 1 to 5');
 if (format === 'email') {
  if (!s.subject) problems.push('email needs a subject');
  if (!s.from_name || !/^[a-z0-9.-]{2,40}$/.test(s.from_local || '')) problems.push('email needs from_name and a from_local like "delivery-notice"');
  if (!(s.content || '').includes('{link}')) problems.push('email content needs {link}');
 }
 const tells = s.tells || [];
 if (tells.length < 2 || tells.length > 4) problems.push('two to four tells');
 for (const t of tells) if (!t.quote || !t.note || !(s.content || '').includes(t.quote)) problems.push(`tell not found word for word in content: ${t.quote}`);
 if (!Array.isArray(s.next_steps) || s.next_steps.length < 2 || s.next_steps.length > 3) problems.push('two or three next steps');
 const q = s.question;
 if (!q || !q.prompt || !Array.isArray(q.choices) || q.choices.length !== 3 || !(q.correct >= 0 && q.correct <= 2) || !q.affirm || !q.gently) problems.push('question needs a prompt, three choices, a correct index, affirm and gently');
 const visible = [s.from_name, s.subject, s.content].join(' ');
 if (BRANDS.test(visible)) problems.push(`names a real brand or agency: ${visible.match(BRANDS)[0]}`);
 const coaching = [s.debrief, ...(s.next_steps || []), ...tells.map(t => t.note), q?.affirm, q?.gently].join(' ');
 if (BANNED_WORDS.test(coaching)) problems.push(`coaching uses a word we don't use: ${coaching.match(BANNED_WORDS)[0]}`);
 if (s.expires_at && Number.isNaN(Date.parse(s.expires_at))) problems.push('expires_at must be a date');
 if (s.context_url && !/^\/[a-z0-9/-]+$/.test(s.context_url)) problems.push('context_url must be a site path');
 return problems;
}

const lit = v => v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`;
const json = v => `${lit(JSON.stringify(v ?? null))}::jsonb`;
const arr = a => `array[${(a || []).map(lit).join(',')}]::text[]`;

export function buildSql(library) {
 const lines = ['-- Generated by scripts/build-practice-seed.mjs from content/practice-library. Do not edit by hand.',
  '-- Inserts each scenario as a DRAFT. Approve them one by one in /admin/ before anything is sent.', 'begin;'];
 for (const [format, scenarios] of Object.entries(library)) {
  for (const s of scenarios) {
   const variant = format === 'email' ? { from_name: s.from_name, from_local: s.from_local } : (s.channel_variant || {});
   lines.push(`with scam as (insert into public.practice_scams(stable_code,name,category) values(${lit(s.code)},${lit(s.name)},${lit(s.category)}) on conflict(stable_code) do update set name=excluded.name returning id)`);
   lines.push(`insert into public.practice_scam_versions(scam_id,version_number,format,difficulty,subject,content,learning_objective,warning_signs,debrief,status,tells,channel_variant,brand_mode,expires_at,generated_by,next_steps,question,context_url)`);
   lines.push(`select scam.id, coalesce((select max(version_number) from public.practice_scam_versions v where v.scam_id=scam.id),0)+1, ${lit(format)}, ${s.difficulty}, ${lit(s.subject)}, ${lit(s.content)}, ${lit(s.learning_objective)}, ${arr((s.tells || []).map(t => t.note))}, ${lit(s.debrief)}, 'draft', ${json(s.tells)}, ${json(variant)}, 'generic', ${s.expires_at ? `${lit(s.expires_at)}::timestamptz` : 'null'}, 'human', ${arr(s.next_steps)}, ${json(s.question)}, ${lit(s.context_url)}`);
   lines.push(`from scam where not exists(select 1 from public.practice_scam_versions v where v.scam_id=scam.id and v.format=${lit(format)});`);
  }
 }
 lines.push('commit;', '');
 return lines.join('\n');
}

export function loadLibrary(dir = `${root}content/practice-library`) {
 const library = {};
 for (const file of readdirSync(dir).filter(f => f.endsWith('.json'))) {
  const format = file.replace(/\.json$/, '');
  if (!FORMATS.includes(format)) throw new Error(`${file}: name the file email.json, text.json or phone.json`);
  library[format] = JSON.parse(readFileSync(`${dir}/${file}`, 'utf8')).scenarios;
 }
 return library;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
 const library = loadLibrary();
 let bad = 0; const codes = new Set();
 for (const [format, scenarios] of Object.entries(library)) for (const s of scenarios) {
  const problems = validateScenario(s, format);
  if (codes.has(`${format}:${s.code}`)) problems.push('duplicate code');
  codes.add(`${format}:${s.code}`);
  for (const p of problems) { console.error(`${format}/${s.code}: ${p}`); bad += 1; }
 }
 if (bad) process.exit(1);
 const sql = buildSql(library);
 if (process.argv.includes('--check')) {
  // In the build: the library must be valid and the generated SQL must match it.
  let current = ''; try { current = readFileSync(`${root}database/practice-seed.sql`, 'utf8'); } catch {}
  if (current !== sql) { console.error('database/practice-seed.sql is out of date. Run npm run practice:seed.'); process.exit(1); }
  process.exit(0);
 }
 writeFileSync(`${root}database/practice-seed.sql`, sql);
 const counts = Object.fromEntries(Object.entries(library).map(([f, s]) => [f, s.length]));
 console.log('practice-seed.sql written', JSON.stringify(counts));
}
